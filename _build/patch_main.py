    for fname, old, new in PATCHES:
        path = os.path.join(DOC, fname)
        with io.open(path, encoding="utf-8") as fh:
            text = fh.read()
        cnt = text.count(old)
        if cnt != 1:
            print("!! %s: pattern found %d times: %s" % (fname, cnt, old[:50]))
            ok = False
            continue
